  function csMerge(target, ru) {
    var tk = Object.keys(target), rk = Object.keys(ru);
    if (tk.length !== rk.length) fail("key count " + tk.length + " vs " + rk.length);
    rk.forEach(function (k) {
      if (!(k in target)) fail("unknown key " + k);
      Object.keys(ru[k]).forEach(function (f) {
        if (!(f in target[k])) fail("unknown field " + k + "." + f);
        target[k][f] = ru[k][f];
      });
    });
  }

