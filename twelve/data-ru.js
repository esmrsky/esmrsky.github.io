  function same(a, b) { return JSON.stringify(a) === JSON.stringify(b); }
  function cite(en, path) {
    if (!Object.prototype.hasOwnProperty.call(REF, en)) fail(path, "no Russian citation for " + en);
    return REF[en];
  }
  function apply(o, k, v, path, skip) {
    var e = o[k], p = path + "." + k;
    if (NONTEXT[k]) { if (v !== undefined && !same(v, e)) fail(p, "key changed"); return; }
    if (typeof e === "string") {
      if (typeof v !== "string" || !v) fail(p, "no translation");
      o[k] = v; return;
    }
    if (typeof e === "number") { if (v !== undefined && v !== e) fail(p, "number changed"); return; }
    if (e && typeof e === "object") { merge(e, v, p, skip); return; }
    fail(p, "English has no such field");
  }
  function merge(en, ru, path, skip) {
    skip = skip || {};
    if (Array.isArray(en)) {
      if (!Array.isArray(ru)) fail(path, "expected an array");
      if (ru.length !== en.length) fail(path, "English has " + en.length + " items, RU has " + ru.length);
      for (var i = 0; i < en.length; i++) apply(en, i, ru[i], path + "[" + i + "]", skip);
      return;
    }
    if (!ru || typeof ru !== "object") fail(path, "expected an object");
    Object.keys(ru).forEach(function (k) { if (!(k in en)) fail(path + "." + k, "English has no such key"); });
    Object.keys(en).forEach(function (k) {
      if (skip[k]) return;
      if (!NONTEXT[k] && !(k in ru) && (typeof en[k] === "string" || (en[k] && typeof en[k] === "object"))) fail(path + "." + k, "missing in RU");
      if (k in ru || NONTEXT[k]) apply(en, k, ru[k], path, skip);
    });
  }

