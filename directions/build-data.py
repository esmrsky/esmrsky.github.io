# Builds directions/data.js from the live homepage cards and the views script,
# so the previews show the real site list, never a hand copy of it.
# Run from the hub root: python3 directions/build-data.py
import json, re, subprocess
from bs4 import BeautifulSoup

html = open('index.html', encoding='utf8').read()
views = open('assets/hub-views.js', encoding='utf8').read()
soup = BeautifulSoup(html, 'html.parser')
accent = {}
for m in re.finditer(r'\.(theme-[a-z0-9-]+)\s*\{\s*--accent:\s*(#[0-9A-Fa-f]{3,8})', html):
    accent.setdefault(m.group(1), m.group(2))
t = lambda el: re.sub(r'\s+', ' ', el.get_text()).strip() if el else ''
sites = []
for a in soup.select('a.bento-card'):
    href = a['href']; m = re.match(r'^/([^/?#]+)/', href)
    if not m or any(s['slug'] == m.group(1) for s in sites): continue
    theme = next((c for c in a['class'] if c.startswith('theme-')), '')
    sites.append(dict(slug=m.group(1), href=href, kind=t(a.select_one('.card-tag')),
        title=t(a.select_one('.card-title')), desc=t(a.select_one('.card-desc')),
        inside=[t(li) for li in a.select('.card-inside li')], accent=accent.get(theme, '#888888'),
        size=3 if 'span-2-2' in a['class'] or 'span-3-1' in a['class'] else 2 if any(c.startswith('span-') for c in a['class']) else 1,
        pills=[t(p) for p in a.select('.card-pills .pill')]))

def grab(name):
    i = views.index('[', views.index('var %s = [' % name)); d = 0
    for j in range(i, len(views)):
        d += {'[': 1, ']': -1}.get(views[j], 0)
        if d == 0: break
    return json.loads(subprocess.check_output(['node', '-e', 'process.stdout.write(JSON.stringify(' + views[i:j+1] + '))']))
sections = [dict(id=x['id'], name=x['en'], note=x['den'], s=x['s']) for x in grab('SECTIONS')]
claims = [dict(n=x['n'], pin=x['pin'], text=x['en'], short=x['sen'], s=x['s']) for x in grab('CLAIMS')]
family = grab('FAMILY')
open('directions/data.js', 'w', encoding='utf8').write(
    '/* Generated by build-data.py from index.html and assets/hub-views.js. Do not edit. */\n'
    'window.ESMRSKY = ' + json.dumps(dict(sites=sites, sections=sections, claims=claims, family=family), ensure_ascii=False) + ';\n')
print(len(sites), 'sites')
print('no section:', [s['slug'] for s in sites if not any(s['slug'] in x['s'] for x in sections)])
print('missing text:', [s['slug'] for s in sites if not s['title'] or not s['desc']])
